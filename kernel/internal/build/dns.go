package build

import (
	"fmt"
	"strings"

	"github.com/luuuuke88/clashmiao/kernel/internal/build/cfg"
	"github.com/luuuuke88/clashmiao/kernel/internal/options"
)

// DNS 服务器的固定 tag（旧内核的隐式契约）。
const (
	TagDNSRemote    = "dns-remote"
	TagDNSDirect    = "dns-direct"
	TagDNSLocal     = "dns-local"
	TagDNSFake      = "dns-fake"
	TagDNSBootstrap = "dns-bootstrap"
)

const (
	fakeIPv4Range = "198.18.0.0/15"
	fakeIPv6Range = "fc00::/18"
	// connectivity 探测域名固定走远程 DNS，并把 TTL 固定住（旧行为）。
	connectivityDomain = "cp.cloudflare.com"
	connectivityTTL    = 3000
)

// dnsInput 是 BuildDNS 的输入。
type dnsInput struct {
	Options *options.Options
	// Egress 是业务出口 tag（常态 select；warp_over_proxy 为 warp）。dns-remote 的 detour 指向它。
	Egress string
	// HasTun 为真才可能生成 dns-fake 与引用 tun-in 的规则。
	HasTun bool
	// DirectDomains 是必须直连解析的域名（各节点 server、WARP 对端域名）；函数内部去重、排序。
	DirectDomains []string
}

// BuildDNS 生成 dns 块（spec §3.4、§5.2、§5.2.1）。
//
// 服务器：dns-remote（detour = 业务出口，否则远程 DNS 会直连泄漏）、dns-direct（无 detour）、dns-local、
// 可选 dns-fake、可选 dns-bootstrap（仅当存在域名型服务器时）。
// 规则顺序：①直连域名 → dns-direct；②fake DNS；③DNS 路由（bypass → dns-direct，block → NOERROR）；
// ④connectivity 探测域名 → dns-remote 并固定 TTL。
func BuildDNS(in dnsInput, warnings *[]string) (*cfg.DNS, error) {
	o := in.Options
	if in.Egress == "" {
		return nil, fmt.Errorf("%s dns: empty egress", PrefixBuildFailed)
	}

	remote, err := ParseDNSAddress(o.RemoteDNSAddress)
	if err != nil {
		return nil, wrapOptionField("remote-dns-address", err)
	}
	direct, err := ParseDNSAddress(o.DirectDNSAddress)
	if err != nil {
		return nil, wrapOptionField("direct-dns-address", err)
	}
	for field, spec := range map[string]DNSServerSpec{"remote-dns-address": remote, "direct-dns-address": direct} {
		if spec.Type == "fakeip" {
			return nil, &options.Error{Msg: field + ": fakeip is generated by enable-fake-dns and cannot be configured as an address"}
		}
	}

	needBootstrap := remote.IsDomain || direct.IsDomain
	var servers []cfg.DNSServer
	servers = append(servers, typedServer(TagDNSRemote, remote, in.Egress))
	servers = append(servers, typedServer(TagDNSDirect, direct, ""))
	servers = append(servers, cfg.DNSServer{Type: "local", Tag: TagDNSLocal})

	fake := o.EnableFakeDNS && in.HasTun
	if fake {
		servers = append(servers, cfg.DNSServer{Type: "fakeip", Tag: TagDNSFake, Inet4Range: fakeIPv4Range, Inet6Range: fakeIPv6Range})
	}
	if needBootstrap {
		ip, port, err := options.ParseBootstrapDNSAddress(o.BootstrapDNSAddress)
		if err != nil {
			return nil, err
		}
		b := cfg.DNSServer{Type: "udp", Tag: TagDNSBootstrap, Server: ip.String()}
		if port != 0 && port != 53 {
			b.ServerPort = int(port)
		}
		servers = append(servers, b)
	}

	var rules []cfg.DNSRule
	// ① 直连域名：节点自己的服务器域名必须直连解析（否则「解析节点域名」要先经过节点）。
	if domains := uniqueSorted(in.DirectDomains); len(domains) > 0 {
		rules = append(rules, withDirectStrategy(cfg.DNSRule{Domain: domains, Action: "route", Server: TagDNSDirect}, o))
	}
	// ② fake DNS：仅 tun 入站的查询；仅线路没有 tun-in 时整条省略。
	if fake {
		rules = append(rules, cfg.DNSRule{Inbound: []string{TagTunIn}, Action: "route", Server: TagDNSFake, DisableCache: true})
	}
	// ③ DNS 路由：智能分流的 bypass 域名用直连 DNS 解析，block 域名直接回空答案。
	if o.EnableDNSRouting {
		for i, r := range o.Rules {
			m, err := r.Matchers()
			if err != nil {
				return nil, wrapRuleError(i, err)
			}
			if !onlyDomainMatchers(m) {
				continue // 带 IP / 端口等条件的规则 DNS 规则表达不了，且放宽会误伤，跳过
			}
			dr := cfg.DNSRule{Domain: m.Domain, DomainSuffix: m.DomainSuffix, DomainRegex: m.DomainRegex, DomainKeyword: m.DomainKeyword}
			switch r.Target() {
			case options.TargetBypass:
				dr.Action, dr.Server = "route", TagDNSDirect
				dr = withDirectStrategy(dr, o)
			case options.TargetBlock:
				dr.Action, dr.Rcode = "predefined", "NOERROR"
			default:
				continue
			}
			rules = append(rules, dr)
		}
	}
	// ④ 探测域名走远程 DNS 并固定 TTL。
	ttl := uint32(connectivityTTL)
	rules = append(rules, withRemoteStrategy(cfg.DNSRule{
		Domain: []string{connectivityDomain}, Action: "route", Server: TagDNSRemote, RewriteTTL: &ttl,
	}, o))

	if o.IndependentDNSCache != options.Default().IndependentDNSCache {
		*warnings = append(*warnings, "independent-dns-cache-ignored: independent_cache is deprecated in sing-box 1.14 and not written")
	}

	return &cfg.DNS{Servers: servers, Rules: rules, Final: TagDNSRemote, Strategy: o.IPv6Mode}, nil
}

func wrapOptionField(field string, err error) error {
	if oe, ok := err.(*options.Error); ok {
		return &options.Error{Msg: field + ": " + oe.Msg}
	}
	return err
}

// typedServer 把解析结果落成服务器；地址是域名时一律交给 dns-bootstrap 解析（绝不指向自己）。
func typedServer(tag string, s DNSServerSpec, detour string) cfg.DNSServer {
	out := cfg.DNSServer{Type: s.Type, Tag: tag, Server: s.Host, ServerPort: s.Port, Path: s.Path}
	if s.IsDomain {
		out.DomainResolver = TagDNSBootstrap
	}
	// local 走系统解析，不拨号，不写 detour；其余按调用方给的 detour（dns-remote 的业务出口）。
	if s.Type != "local" {
		out.Detour = detour
	}
	return out
}

func onlyDomainMatchers(m options.Matchers) bool {
	hasDomain := len(m.Domain)+len(m.DomainSuffix)+len(m.DomainRegex)+len(m.DomainKeyword) > 0
	other := len(m.IPCIDR)+len(m.Port)+len(m.PortRange)+len(m.Network)+len(m.Protocol) > 0
	return hasDomain && !other
}

func uniqueSorted(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		s = strings.ToLower(strings.TrimSpace(s))
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sortStrings(out)
	return out
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// ---- 弃用字段集中地 ----
//
// DNS 规则动作里的 strategy 在 sing-box 1.14 已弃用、1.16 移除。remote / direct-dns-domain-strategy
// 默认为空，只有用户显式设置时才写；两个函数是仅有的写入点，升到 1.16 前要迁成全局 dns.strategy 或服务器级字段。

func withDirectStrategy(r cfg.DNSRule, o *options.Options) cfg.DNSRule {
	r.Strategy = o.DirectDNSDomainStrategy
	return r
}

func withRemoteStrategy(r cfg.DNSRule, o *options.Options) cfg.DNSRule {
	r.Strategy = o.RemoteDNSDomainStrategy
	return r
}
